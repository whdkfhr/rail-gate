package com.railgate.reservation.infra.seat;

/**
 * 다좌석 선점 시도의 결과 (I-9 전부-또는-전무).
 *
 * <p>중간 상태가 없다는 점이 핵심이다. "3석 중 2석 성공" 같은 결과는 존재하지 않는다.
 * 그래서 결과 타입도 성공한 좌석 수를 담지 않는다 — 담을 수 있는 값이 요청 좌석 수 아니면 0 뿐이다.
 */
public enum MultiSeatHoldOutcome {

    /** 요청한 좌석 <b>전부</b>를 선점했다. */
    HELD,

    /**
     * 요청한 좌석 중 하나 이상을 선점할 수 없어 <b>전부</b> 실패했다.
     * 이미 갱신된 행이 있었다면 롤백되어 아무 좌석도 점유하지 않는다.
     *
     * <p>경합 실패는 오류가 아니라 정상 동작이며 앱 계층이 409 로 매핑한다
     * (CLAUDE.md 규칙 21).
     */
    SEAT_UNAVAILABLE
}
