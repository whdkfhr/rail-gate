-- 홀드 단위 좌석 조회 인덱스 (FR-2.5 자발적 해제).
--
-- 해제는 "이 홀드에 묶인 좌석" 을 찾는다. 기존 idx_seat_inventory_held_by (held_by, status)
-- 로도 답은 나오지만, 그 인덱스는 대상 사용자의 활성 좌석을 전부 스캔한 뒤
-- hold_id 로 걸러낸다. 즉 비용이 O(홀드 좌석 수) 가 아니라 O(사용자 활성 좌석 수) 다.
--
-- 사용자별 활성 좌석 수의 상한은 I-12(1인당 4석)가 강제할 값인데 아직 구현되지 않았다.
-- 따라서 "사용자별 활성 좌석은 항상 적다" 를 전제로 삼을 수 없다.
-- 한 사용자가 여러 스케줄에 걸쳐 많은 좌석을 잡고 있는 분포에서 현재 인덱스는 선형으로 나빠진다.
--
-- MySQL 8.4, 좌석 100,000행 / 활성 20,000행 / 홀드 5,000개(홀드당 4석) 실측.
-- 두 경우 모두 대상 홀드는 4석이고, 다른 것은 그 홀드를 가진 사용자의 활성 좌석 수뿐이다.
--
--   대상 사용자의 활성 좌석이 4석 (일반 분포)
--     (held_by, status)  내부 스캔     4행 -> 반환 4행
--     (hold_id)          내부 스캔     4행 -> 반환 4행
--
--   대상 사용자의 활성 좌석이 2,000석 (홀드 500개, 불리 분포)
--     (held_by, status)  내부 스캔 2,000행 -> 반환 4행   ← 사용자 활성 좌석 수에 비례
--     (hold_id)          내부 스캔     4행 -> 반환 4행   ← 홀드 좌석 수에만 비례
--
-- 실행 시간은 보조 수치일 뿐이며, 판단 근거는 스캔 행 수와 데이터 증가 시의 복잡도다.
-- (참고로 불리 분포에서 3회 중앙값은 1.61ms 대 0.027ms 였다.)
--
-- 이 인덱스의 역할은 후보 범위를 홀드 좌석 수로 제한하는 "탐색" 이다.
-- 키 컬럼을 (hold_id) 하나로 둔 이유:
--   - InnoDB 보조 인덱스에는 PK 인 id 가 암묵적으로 포함된다.
--     후보 조회가 읽는 값은 id 뿐이므로 id 를 키 컬럼으로 다시 적을 이유가 없다.
--   - 후보 조회는 held_by 와 status 도 검사한다. 이 인덱스가 그 두 컬럼을 갖지 않으므로
--     전체 쿼리의 covering index 가 아니다. 그렇게 부르면 안 된다.
--   - 잠금 순서는 이 인덱스가 아니라, 후보를 Java 에서 id 오름차순으로 정렬한 뒤
--     FORCE INDEX (PRIMARY) 로 갱신하는 것이 보장한다 (CLAUDE.md 규칙 2·3).
--     따라서 잠금 순서도 인덱스의 명시적 id 컬럼에 의존하지 않는다.
--
-- 기존 (held_by, status) 인덱스는 삭제하지 않는다. 다른 경로의 영향까지 측정한 뒤 판단한다.
-- ---------------------------------------------------------------------------

ALTER TABLE seat_inventory
    ADD KEY idx_seat_inventory_hold (hold_id);
